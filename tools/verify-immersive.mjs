import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const base = process.argv[2] || 'http://127.0.0.1:4173'
const out = fileURLToPath(new URL('../.preview-out/immersive/', import.meta.url))
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const results = [], errors = []
const load = async page => {
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base, { waitUntil: 'networkidle' })
  await page.waitForFunction(() => window.__DOUBAO?.state().ready)
  await page.waitForTimeout(900)
}
const chapter = async (page, id, extra = 0) => {
  await page.evaluate(({ id, extra }) => window.__DOUBAO.scroll.scrollTo(document.getElementById(id).offsetTop + extra, { immediate: true }), { id, extra })
  await page.waitForTimeout(100)
  await page.waitForFunction(() => {
    const state = window.__DOUBAO.state()
    return Math.abs(state.framing - state.target) < .005
  }, undefined, { timeout: 10000 })
  await page.waitForTimeout(350)
}
const pixels = (page, point) => page.evaluate(point => {
  const stage = window.__DOUBAO.stage; stage.render()
  const gl = stage.renderer.getContext(), scale = gl.drawingBufferWidth / innerWidth
  const size = Math.round(90 * scale), data = new Uint8Array(size * size * 4)
  gl.readPixels(Math.round((point.x - 45) * scale), Math.round((innerHeight - point.y - 45) * scale), size, size, gl.RGBA, gl.UNSIGNED_BYTE, data)
  return Array.from(data)
}, point)

try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await load(page)
  const initial = await page.evaluate(() => ({ state: window.__DOUBAO.state(), nav: getComputedStyle(document.getElementById('nav')).backgroundColor, overflow: document.documentElement.scrollWidth > innerWidth }))
  assert.equal(initial.state.faceVisible, true)
  assert.equal(initial.state.characterVisible, false, 'Only the video portrait should render in the hero')
  assert.equal(initial.nav, 'rgba(0, 0, 0, 0)', 'Navigation must not create an opaque strip')
  assert.equal(initial.overflow, false)
  await page.locator('#motionToggle').click()
  await page.waitForFunction(() => document.getElementById('faceSrc').paused)
  assert.equal(await page.evaluate(() => document.getElementById('faceSrc').paused), true)
  await page.screenshot({ path: out + '01-desktop-hero.png' })
  const cheek = await page.evaluate(() => window.__DOUBAO.faceLayer.getScreenPoint(.39, .46))
  await page.mouse.move(cheek.x, cheek.y)
  await page.waitForTimeout(200)
  const before = await pixels(page, cheek)
  await page.mouse.down()
  await page.mouse.move(cheek.x + 55, cheek.y - 18, { steps: 10 })
  await page.waitForTimeout(350)
  assert.ok(await page.evaluate(() => window.__DOUBAO.faceLayer.pinchStrength > .8), 'Paused video must still support cheek dragging')
  const pressed = await pixels(page, cheek)
  const changed = before.filter((value, i) => Math.abs(value - pressed[i]) > 3).length
  assert.ok(changed > 1000, `Cheek pixels must visibly deform, changed channels: ${changed}`)
  await page.screenshot({ path: out + '02-cheek-drag.png' })
  await page.mouse.up(); await page.waitForTimeout(850)
  assert.ok(await page.evaluate(() => Math.abs(window.__DOUBAO.faceLayer.pinchStrength) < .03))
  assert.ok((await page.locator('#experiencePass b').textContent()).startsWith('1'))
  results.push('Hero: transparent navigation, single face, visible cheek deformation while paused, spring release')

  await page.locator('#heroEnter').click(); await page.waitForTimeout(1200)
  const chat = await page.locator('#heroAsk').boundingBox()
  assert.ok(Math.abs(chat.x + chat.width / 2 - 720) < 3 && chat.width >= 700, 'Chat should have a centered, comfortable layout')
  assert.equal(await page.evaluate(() => window.__DOUBAO.state().faceVisible), false)
  assert.equal(await page.evaluate(() => window.__DOUBAO.state().characterVisible), true)
  await page.screenshot({ path: out + '03-desktop-chat.png' })
  const input = page.locator('#askInput')
  await input.fill('中文输入测试'); await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  assert.equal(await page.locator('.ask-bubble--user').count(), 0)
  await input.fill('帮我安排一下今天'); await input.press('Enter')
  await page.getByRole('button', { name: '停止回复', exact: true }).click()
  const count = await page.locator('.ask-bubble').count(); await page.waitForTimeout(600)
  assert.equal(await page.locator('.ask-bubble').count(), count)
  await page.locator('#chatReset').click()
  assert.equal(await page.locator('.ask-bubble').count(), 1)
  results.push('Chat: centered over the body, no second face, IME protection, stop and reset')

  for (const [id, shot] of [['positioning', 'neck'], ['scenes', 'waist'], ['alcoves', 'legs'], ['characterStudio', 'body']]) {
    await chapter(page, id)
    const state = await page.evaluate(() => window.__DOUBAO.state())
    assert.equal(state.activeShot, shot); assert.equal(state.faceVisible, false); assert.equal(state.characterVisible, true)
    await page.screenshot({ path: out + `04-${shot}.png` })
  }
  for (const index of [1, 2, 0]) {
    await page.locator(`[data-character-view="${index}"]`).click(); await page.waitForTimeout(800)
    assert.equal(await page.locator(`[data-character-view="${index}"]`).getAttribute('aria-pressed'), 'true')
    const layers = await page.evaluate(() => {
      const layers = []; window.__DOUBAO.character.object3d.traverseVisible(mesh => { if (mesh.material?.uniforms?.uOpacity?.value > .01) layers.push(mesh.material.uniforms.uMap.value.image.src) }); return layers
    })
    assert.equal(layers.length, 1, 'Each character view must render exactly one image')
    assert.ok(layers[0].includes(['doubao_front', 'doubao_side', 'doubao_back'][index]))
  }
  await page.screenshot({ path: out + '05-desktop-whole-body.png' })
  results.push('Character: shoulder → waist → legs → entire body, three views, one image at a time')

  await chapter(page, 'productTour')
  assert.equal(await page.locator('#productTabs [role="tab"]').count(), 8)
  await page.locator('#productTab0').focus(); await page.keyboard.press('End')
  assert.equal(await page.locator('#productTab7').getAttribute('aria-selected'), 'true')
  assert.ok((await page.locator('#productDetail').innerText()).includes('屏幕共享'))
  await page.locator('#productTry').click(); await page.waitForTimeout(1200)
  assert.ok((await input.inputValue()).includes('构图'))
  results.push('Product introduction: eight capabilities, keyboard tabs and draft transfer to chat')

  await chapter(page, 'playground')
  await page.locator('[data-recipe="task"][data-value*="邮件"]').click()
  await page.locator('[data-recipe="tone"][data-value*="直接"]').click()
  await page.locator('[data-recipe="format"][data-value*="三个"]').click()
  const prompt = await page.locator('#recipeOutput').inputValue()
  assert.ok(prompt.includes('邮件') && prompt.includes('直接') && prompt.includes('三个'))
  await page.locator('#recipeSend').click(); await page.waitForTimeout(1200)
  assert.equal(await input.inputValue(), prompt)
  await chapter(page, 'playground')
  await page.locator('[data-play="story"]').click()
  await page.locator('#storyChoices button').first().click(); await page.locator('#storyChoices button').first().click()
  assert.ok((await page.locator('.story-ending').innerText()).includes('01'))
  await page.locator('#storyRestart').click()
  assert.equal(await page.locator('#storyChoices button').count(), 2)
  await page.locator('#storyChoices button').last().click(); await page.locator('#storyChoices button').last().click()
  assert.ok((await page.locator('.story-ending').innerText()).includes('04'))
  await page.waitForTimeout(450)
  await page.screenshot({ path: out + '06-branching-story.png' })
  results.push('Playground: prompt composition and chat handoff, branching outcomes and restart')

  await page.locator('[data-play="focus"]').click()
  await page.locator('#focusGoal').fill('写完一个开头'); await page.locator('#focusStart').click()
  await page.waitForTimeout(1500)
  assert.notEqual(await page.locator('#focusTime').textContent(), '05:00')
  await page.locator('#focusStart').click()
  const paused = await page.locator('#focusTime').textContent(); await page.waitForTimeout(1100)
  assert.equal(await page.locator('#focusTime').textContent(), paused)
  await page.locator('#focusStart').click()
  await page.clock.setSystemTime(Date.now() + 301000); await page.waitForTimeout(500)
  assert.equal(await page.locator('#focusTime').textContent(), '00:00')
  assert.ok((await page.locator('#focusStatus').textContent()).includes('完成'))
  await page.locator('#focusReset').click()
  assert.equal(await page.locator('#focusTime').textContent(), '05:00')
  await page.screenshot({ path: out + '07-focus-clock.png' })
  results.push('Focus clock: real countdown, pause, resume, elapsed-time completion and reset')

  await chapter(page, 'faq')
  const faq = page.locator('.faq-item h3 button').first(); await faq.click()
  assert.equal(await faq.getAttribute('aria-expanded'), 'true'); assert.equal(await page.locator('#faqAnswer0').isVisible(), true)
  await faq.click(); assert.equal(await page.locator('#faqAnswer0').isVisible(), false)
  await page.locator('#siteMenu').click(); assert.equal(await page.locator('#exploreMenu').isVisible(), true)
  await page.keyboard.press('Escape'); assert.equal(await page.locator('#exploreMenu').isVisible(), false)
  await chapter(page, 'capabilities'); await page.locator('[data-wb="write"]').click(); await page.locator('[data-write-op="short"]').click()
  assert.ok((await page.locator('[data-write-draft]').innerText()).length < 45)
  results.push('FAQ, accessible navigation and existing writing workbench remain usable')

  for (const width of [390, 768]) {
    const mobile = await browser.newPage({ viewport: { width, height: 900 }, hasTouch: true, isMobile: width < 600 })
    await load(mobile)
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    const face = await mobile.evaluate(() => window.__DOUBAO.faceLayer.getScreenPoint(.65, .46))
    const headline = await mobile.locator('.s-hero__dock').boundingBox()
    assert.ok(headline.y > face.y + 30 || headline.x + headline.width < face.x, 'Hero copy must leave the central face clear')
    await mobile.screenshot({ path: out + `08-${width}-hero.png` })
    const cdp = await mobile.context().newCDPSession(mobile)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: face.x, y: face.y }] })
    await mobile.waitForTimeout(250)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: face.x - 20, y: face.y + 12 }] })
    await mobile.waitForTimeout(220)
    assert.ok(await mobile.evaluate(() => window.__DOUBAO.faceLayer.pinchStrength > .5), 'Touch cheek drag should work')
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await mobile.locator('#heroEnter').click(); await mobile.waitForTimeout(1300)
    assert.equal(await mobile.evaluate(() => window.__DOUBAO.state().faceVisible), false)
    const bounds = await mobile.locator('#heroAsk').boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1)
    await chapter(mobile, 'characterStudio', width < 600 ? 480 : 0)
    assert.equal(await mobile.evaluate(() => window.__DOUBAO.state().activeShot), 'body')
    await mobile.screenshot({ path: out + `09-${width}-whole-body.png` })
    await mobile.close()
    results.push(`${width}px: no overflow, clear face, touch drag, centered chat and full body`)
  }
  const reduced = await browser.newPage({ viewport: { width: 390, height: 900 }, reducedMotion: 'reduce' })
  await load(reduced)
  assert.equal(await reduced.locator('#motionToggle').isDisabled(), true)
  assert.equal(await reduced.evaluate(() => document.getElementById('faceSrc').paused), true)
  await chapter(reduced, 'characterStudio', 480)
  assert.equal(await reduced.evaluate(() => window.__DOUBAO.state().activeShot), 'body')
  results.push('Reduced motion preserves content and the complete character without autoplay')
  const fallback = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await fallback.route('**/*.mp4', route => route.abort()); await load(fallback)
  assert.equal(await fallback.evaluate(() => document.documentElement.dataset.faceRendered), '1')
  await fallback.screenshot({ path: out + '10-video-fallback.png' })
  assert.deepEqual(errors, [])
  results.push('Video failure falls back to a visible portrait; no browser exceptions')
  await writeFile(out + 'report.json', JSON.stringify({ results, errors }, null, 2))
  console.log(JSON.stringify({ passed: results.length, results, screenshots: out }, null, 2))
} finally { await browser.close() }
