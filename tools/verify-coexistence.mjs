import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const base = process.argv[2] || 'http://127.0.0.1:4173'
const out = fileURLToPath(new URL('../.preview-out/coexistence/', import.meta.url))
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const results = [], errors = []
async function open(options = {}) {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, ...options })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base)
  await page.waitForFunction(() => document.documentElement.dataset.bootState === 'entered' && window.__DOUBAO?.character?.ready)
  return page
}
async function go(page, t) {
  await page.evaluate(t => window.__DOUBAO.scroll.scrollTo(window.__DOUBAO.anchorMap.toScroll(t), { immediate: true }), t)
  await page.waitForTimeout(1400)
}
