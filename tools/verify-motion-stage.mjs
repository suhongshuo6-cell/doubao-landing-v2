import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const base = process.argv[2] || 'http://127.0.0.1:4173'
const out = fileURLToPath(new URL('../.preview-out/motion-stage/', import.meta.url))
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const results = [], errors = []
async function open(options = {}) {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, ...options })
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(base)
  await page.waitForFunction(() => document.documentElement.dataset.bootState === 'entered' && window.__DOUBAO?.character?.ready)
  return page
}
async function scrollGallery(page, p) {
  await page.evaluate(p => { const el = document.getElementById('resultRunway'); window.__DOUBAO.scroll.scrollTo(el.getBoundingClientRect().top + scrollY + (el.offsetHeight - innerHeight) * p, { immediate: true }) }, p)
  await page.waitForTimeout(1300)
}
try {
  const page = await open()
  await page.screenshot({ path: out + '01-hero-discover.png' })
  await page.locator('#motionExplore').click()
  await page.waitForTimeout(1600)
  assert.equal(await page.locator('#resultRunway').getAttribute('data-phase'), 'scatter')
  const first = await page.locator('[data-result="0"]').getAttribute('style')
  await page.screenshot({ path: out + '02-cards-scatter.png' })
  await scrollGallery(page, .48)
  assert.equal(await page.locator('#resultRunway').getAttribute('data-phase'), 'gather')
  assert.notEqual(await page.locator('[data-result="0"]').getAttribute('style'), first)
  const sticky = await page.locator('.result-sticky').boundingBox()
  assert.ok(Math.abs(sticky.y) < 2, 'Gallery must remain pinned to its own runway while scrolling')
  const bounds = await page.locator('.result-card').evaluateAll(items => items.map(el => { const r = el.getBoundingClientRect(); return { x: r.x, right: r.right } }))
  assert.ok(bounds.every(r => r.x > 700 && r.right < 1441), 'Desktop results stay beside the portrait')
  await page.screenshot({ path: out + '03-cards-gather.png' })
  await scrollGallery(page, .93)
  assert.equal(await page.locator('#resultRunway').getAttribute('data-phase'), 'focus')
  await page.locator('[data-result="0"]').click()
  assert.match(await page.locator('[data-result="0"]').getAttribute('class'), /is-flipped/)
  await page.waitForTimeout(800)
  await page.screenshot({ path: out + '04-card-flipped.png' })
  await page.locator('#resultNext').click()
  assert.equal(await page.locator('#resultRunway').getAttribute('data-selected'), '1')
  await page.locator('[data-result="1"]').focus(); await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('#resultRunway').getAttribute('data-selected'), '2')
  await page.locator('#resultUse').click(); await page.waitForTimeout(1400)
  assert.match(await page.locator('#askInput').inputValue(), /不赶路的周末/)
  results.push('Scroll composition: scatter → gather → focus, sticky positioning, portrait-safe bounds, flip, keyboard navigation and real chat draft')

  await page.locator('#artInvitation').click()
  assert.equal(await page.locator('#playPanel-art').isVisible(), true)
  assert.equal(await page.locator('[data-play-panel="recipe"]').isVisible(), false)
  await page.locator('[data-art-scene="city"]').click(); await page.locator('[data-art-palette="blue"]').click()
  assert.equal(await page.locator('#artPoster').getAttribute('data-scene'), 'city')
  assert.equal(await page.locator('#artPoster').getAttribute('data-palette'), 'blue')
  const before = await page.locator('#artCanvas svg').innerHTML()
  await page.locator('#artSun').focus(); await page.keyboard.press('ArrowLeft')
  assert.notEqual(await page.locator('#artCanvas svg').innerHTML(), before)
  const sun = await page.locator('#artSun').boundingBox()
  await page.mouse.move(sun.x + sun.width / 2, sun.y + sun.height / 2); await page.mouse.down(); await page.mouse.move(sun.x + sun.width / 2 - 30, sun.y + sun.height / 2 + 28, { steps: 8 }); await page.mouse.up()
  assert.ok(Number(await page.locator('#artLight').inputValue()) < 405)
  await page.waitForTimeout(900)
  await page.locator('#artPoster').scrollIntoViewIfNeeded()
  await page.screenshot({ path: out + '05-art-director.png' })
  const downloadPromise = page.waitForEvent('download')
  await page.locator('#artExport').click()
  const download = await downloadPromise; await download.saveAs(out + '06-my-daydream.png')
  const png = await readFile(out + '06-my-daydream.png')
  assert.equal(png.readUInt32BE(16), 1200); assert.equal(png.readUInt32BE(20), 1440)
  assert.match(await page.locator('#artStatus').textContent(), /已保存/)
  await page.locator('#artShuffle').click()
  assert.notEqual(await page.locator('#artPoster').getAttribute('data-scene'), 'city')
  await page.locator('#artPrompt').click(); await page.waitForTimeout(1400)
  assert.match(await page.locator('#askInput').inputValue(), /主题.*配色的海报/)
  results.push('Art playground: themes, palettes, pointer and keyboard sun placement, changed artwork, real 1200×1440 PNG export, shuffle and chat draft')

  await page.locator('#playTab-art').click(); await page.locator('#playTab-art').press('Home')
  assert.equal(await page.locator('#playTab-recipe').getAttribute('aria-selected'), 'true')
  assert.equal(await page.locator('#playPanel-art').isVisible(), false)
  results.push('New playground tab coexists with original recipes, stories, focus and keyboard tab navigation')
  await page.locator('.day-tab[data-day="evening"]').click(); await page.waitForTimeout(1000)
  assert.equal(await page.locator('#daySky').getAttribute('data-time'), 'evening')
  assert.equal(await page.locator('.day-sky__clock').textContent(), '21:00')
  await page.screenshot({ path: out + '07-evening-sky.png' })
  results.push('Day stage: slider/tabs also move the sun, moon, clock and sky composition')
  await page.close()

  const mobile = await open({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth), 390)
  const mainButton = await mobile.locator('#heroEnter').boundingBox(), exploreButton = await mobile.locator('#motionExplore').boundingBox()
  assert.ok(mainButton.x + mainButton.width < exploreButton.x, 'Mobile entry buttons must not overlap')
  await scrollGallery(mobile, .4)
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await mobile.screenshot({ path: out + '08-mobile-gallery.png' })
  await mobile.locator('#artInvitation').click(); await mobile.locator('[data-art-scene="night"]').click()
  await mobile.locator('#artPoster').scrollIntoViewIfNeeded(); await mobile.waitForTimeout(850)
  const art = await mobile.locator('#artPoster').boundingBox()
  assert.ok(art.x >= 0 && art.x + art.width < 391)
  assert.equal(await mobile.locator('#artSun').evaluate(el => getComputedStyle(el).touchAction), 'none')
  await mobile.screenshot({ path: out + '09-mobile-art.png' })
  await mobile.close()
  results.push('Mobile: gallery and artwork fit, body remains present, sun drag reserves its own touch gesture')

  const reduced = await open({ reducedMotion: 'reduce' })
  await scrollGallery(reduced, 0)
  const transform = await reduced.locator('[data-result="0"]').getAttribute('style')
  await reduced.waitForTimeout(800)
  assert.equal(await reduced.locator('[data-result="0"]').getAttribute('style'), transform)
  await reduced.locator('[data-result="0"]').click()
  assert.ok(await reduced.locator('.result-card__inner').first().evaluate(el => parseFloat(getComputedStyle(el).transitionDuration) < .001))
  await reduced.close()
  results.push('Reduced motion: static focus layout, no floating, no flip transition, all controls remain available')
  assert.deepEqual(errors, [])
  await writeFile(out + 'report.json', JSON.stringify({ passed: results.length, results, errors }, null, 2))
  console.log(JSON.stringify({ passed: results.length, results, errors }, null, 2))
} finally { await browser.close() }
